/** Browser-side client for the v1 REST API. Every UI mutation goes through here. */

export interface FieldErrorDetail {
  field: string;
  message: string;
}

export class ApiError extends Error {
  constructor(
    readonly status: number,
    readonly code: string,
    message: string,
    readonly fieldErrors: FieldErrorDetail[] = [],
  ) {
    super(message);
  }

  /** One readable line including field-level problems, for inline error text. */
  describe(): string {
    if (!this.fieldErrors.length) return this.message;
    return `${this.message}: ${this.fieldErrors.map((e) => `${e.field} ${e.message}`).join("; ")}`;
  }
}

export async function api<T = unknown>(method: "GET" | "POST" | "PATCH" | "PUT" | "DELETE", path: string, body?: unknown): Promise<T> {
  const res = await fetch(`/api/v1${path}`, {
    method,
    headers: body === undefined ? undefined : { "content-type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const json = await res.json().catch(() => null);
  if (!res.ok) {
    const err = json?.error ?? {};
    throw new ApiError(res.status, err.code ?? "error", err.message ?? `Request failed (${res.status})`, err.details?.fieldErrors ?? []);
  }
  return json as T;
}

export function errorMessage(e: unknown): string {
  return e instanceof ApiError ? e.describe() : e instanceof Error ? e.message : String(e);
}

export interface UploadedFile {
  id: string;
  name: string;
  contentType: string;
  sizeBytes: number;
  detectedFormat: string;
}

/**
 * Upload files through the multipart endpoint.
 *
 * Kept separate from `api()` because FormData must not get a JSON content-type header — the
 * boundary is generated by the browser and setting the header by hand breaks the parse.
 */
export async function upload(files: File[] | FileList, folderId?: string | null): Promise<UploadedFile[]> {
  const form = new FormData();
  for (const file of Array.from(files)) form.append("file", file);
  if (folderId) form.append("folderId", folderId);

  const res = await fetch("/api/v1/files", { method: "POST", body: form });
  const json = await res.json().catch(() => null);
  if (!res.ok) {
    const err = json?.error ?? {};
    throw new ApiError(res.status, err.code ?? "error", err.message ?? `Upload failed (${res.status})`);
  }
  return (json as { items: UploadedFile[] }).items;
}

/** Where a stored file's bytes live, for `<img src>` and download links. */
export const fileContentUrl = (fileId: string) => `/api/v1/files/${fileId}/content`;

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  const units = ["KB", "MB", "GB"];
  let value = bytes / 1024;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit++;
  }
  return `${value < 10 ? value.toFixed(1) : Math.round(value)} ${units[unit]}`;
}
